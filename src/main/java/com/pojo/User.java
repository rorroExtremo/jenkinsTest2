package com.pojo;

public class User {
	
	private int id;
	private String nombre;
	private int edad;
	private String email;
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getNombre() {
		return nombre;
	}
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	public int getEdad() {
		return edad;
	}
	public void setEdad(int edad) {
		this.edad = edad;
	}
	public String getEmail() {
		return email;
	}
	public void setEmail(String email) {
		this.email = email;
	}
	
	public String toString() {
		return "id:: "+this.id
				+" nombre:: "+this.nombre
				+" edad:: "+this.edad
				+" email:: "+this.email;
	}

}
